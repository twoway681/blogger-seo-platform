'use strict';
// llms.txt generator (llmstxt.org convention): a Markdown file that tells AI
// crawlers and assistants what a site covers, with links to its key content.
// Blogger cannot host arbitrary root files, so the platform generates the file;
// the README covers serving it from the platform's own public URL or a mirror host.

function stripHtml(h) {
  return String(h || '').replace(/<[^>]+>/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&#39;|&quot;/g, "'").replace(/\s+/g, ' ').trim();
}

function firstParagraphText(html) {
  const m = String(html || '').match(/<p[^>]*>([\s\S]*?)<\/p>/i);
  return stripHtml(m ? m[1] : html);
}

function summarize(post, max = 180) {
  const s = (post.meta_description || firstParagraphText(post.html) || '').trim();
  return s.length > max ? s.slice(0, max - 3).replace(/\s+\S*$/, '') + '...' : s;
}

// posts: rows with title, html, meta_description, status, published_url.
// Only posts that are actually live (published or dry-run published with a URL) are listed.
function generateLlmsTxt({ blog, posts, generatedAt = new Date() }) {
  const name = blog.name || String(blog.url || 'My blog').replace(/^https?:\/\//, '').replace(/\..*$/, '');
  const home = String(blog.url || '').replace(/\/$/, '');
  const lines = [`# ${name}`, ''];
  lines.push(`> ${name} is a blog published on Blogger at ${home}. This file follows the llms.txt convention so AI assistants and crawlers can understand what the blog covers and cite its posts.`, '');
  const live = (posts || []).filter((p) => p.published_url && (p.status === 'published' || p.status === 'live_dry_run'));
  if (live.length) {
    lines.push('## Posts', '');
    for (const p of live) {
      const sum = summarize(p);
      lines.push(`- [${(p.title || 'Untitled').trim()}](${p.published_url})${sum ? `: ${sum}` : ''}`);
    }
    lines.push('');
  }
  lines.push('## Site', '');
  lines.push(`- Home: ${home}`);
  lines.push(`- Sitemap: ${home}/sitemap.xml`);
  lines.push(`- Generated by Blogsmith on ${generatedAt.toISOString().slice(0, 10)}`);
  lines.push('');
  return lines.join('\n');
}

module.exports = { generateLlmsTxt, summarize };
